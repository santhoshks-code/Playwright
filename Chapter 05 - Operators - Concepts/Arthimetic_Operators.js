let a = 20;
let b = 10;

console.log(a + b); // Output: 30

let sum = a + b;
let multiplication = a * b;
let subtraction = a - b;
let division = a / b;

console.log(sum);   
console.log(multiplication);
console.log(subtraction);
console.log(division);

//Modulus operator - it will return the remainder of the division
console.log(a % b); // Output: 0
console.log(13 % 7); // Output: 3
console.log(100 % 2); // Output: 0  
console.log(101 % 2); // Output: 1

//Exponentiation operator - it will return the result of raising the first operand to the power of the second operand
console.log(a ** b); // Output: 10240000000000
console.log(2 ** 3); // Output: 8