// Comparison Operators
let a = 10;
let b = 20;
console.log(a == b); // Output: false
console.log(a != b); // Output: true
console.log(a < b); // Output: true
console.log(a > b); // Output: false
console.log(a <= b); // Output: true
console.log(a >= b); // Output: false

// Strict Comparison Operators      
console.log(a === b); // Output: false

//loose comparison operator
console.log(a == b); // Output: false   

//Assignment Operators
let x = 10;
x = "Academy";
console.log(x); // Output: Academy

console.log(3 > 5); // Output: false
console.log(3 < 5); // Output: true
console.log(3 >= 5); // Output: false
console.log(3 <= 5); // Output: true
console.log(3 == 5); // Output: false
console.log(3 != 5); // Output: true

console.log(3 === 5); // Output: false
console.log(3 == 5); // Output: true

// loose comparison operator check with either value or type
// strict comparison operator check with both value and type

console.log(5 != "5"); // Output: false
console.log(5 !== "5"); // Output: true    
console.log(5 === "5"); // Output: false