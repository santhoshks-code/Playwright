/*Four types of functions in JavaScript:
1.	No return type: No arguments
2.	With return type: No arguments
3.	With argument, No return type:
4.	With arguments and with return type:
*/
function sayHello(name) {
    console.log (name);
}

// Called the function with an argument
name = "Alice";
sayHello(name); // Output: Hello, Alice!
sayHello("Pramoddutta"); // Output: Hello, Pramoddutta!
sayHello("John"); // Output: Hello, John!